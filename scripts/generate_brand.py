"""Generate outlined brand artwork: uv run scripts/generate_brand.py.

Typeface: Geist, Fontsource package 5.3.0, SIL OFL 1.1 (branding/OFL.txt).
The symbol uses the same font's o, with a custom diagonal instead of font fallback.
"""
from io import BytesIO
from math import hypot
from pathlib import Path
import json

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.roundingPen import RoundingPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'branding/Geist-Latin-Variable.woff2'
PUBLIC = ROOT / 'public/brand'
WEIGHT = 500
SLASH_WIDTH = 94
TRACKING = -14
OPTICAL = [-10, -16, -20, 2, -16, -25, 0]


def outline(glyphs, name: str, matrix: tuple) -> str:
    pen = SVGPathPen(glyphs)
    glyphs[name].draw(TransformPen(RoundingPen(pen, roundFunc=lambda x: round(x, 2)), matrix))
    return pen.getCommands()


def slash_points() -> list[tuple[float, float]]:
    # An eight-unit optical overshoot keeps the slash on the o's baseline/x-height.
    ax, ay, bx, by = 102, 8, 486, 524
    length = hypot(bx - ax, by - ay)
    nx, ny = -(by - ay) / length * SLASH_WIDTH / 2, (bx - ax) / length * SLASH_WIDTH / 2
    return [(ax + nx, ay + ny), (bx + nx, by + ny), (bx - nx, by - ny), (ax - nx, ay - ny)]


def polygon(points: list[tuple[float, float]], dx: float, top: float) -> str:
    return 'M' + 'L'.join(f'{x + dx:.2f} {top - y:.2f}' for x, y in points) + 'Z'


def svg(path: str, width: float, height: float, fill: str = 'currentColor') -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width:.2f} {height:.2f}" '
            f'fill="{fill}" role="img" aria-label="Demotif"><title>Demotif</title>'
            f'<path d="{path}"/></svg>\n')


def main() -> None:
    font = instantiateVariableFont(TTFont(FONT), {'wght': WEIGHT}, inplace=True)
    font.flavor = None
    buffer = BytesIO()
    font.save(buffer)
    face = hb.Face(buffer.getvalue())
    shaped_font = hb.Font(face)
    shaped_font.scale = (font['head'].unitsPerEm, font['head'].unitsPerEm)
    hb.ot_font_set_funcs(shaped_font)
    text = hb.Buffer()
    text.add_str('Demotif')
    text.guess_segment_properties()
    hb.shape(shaped_font, text, {'liga': False})
    glyphs, order = font.getGlyphSet(), font.getGlyphOrder()
    x = 0
    placements = []
    bounds = []
    for i, (info, position) in enumerate(zip(text.glyph_infos, text.glyph_positions, strict=True)):
        name = order[info.codepoint]
        pen = BoundsPen(glyphs)
        glyphs[name].draw(pen)
        dx = x + position.x_offset
        placements.append((name, dx, position.y_offset, info.cluster))
        bounds.append((pen.bounds[0] + dx, pen.bounds[1], pen.bounds[2] + dx, pen.bounds[3]))
        x += position.x_advance + TRACKING + OPTICAL[i]
    minimum = min(b[0] for b in bounds)
    maximum = max(b[2] for b in bounds)
    top, bottom, padding = max(b[3] for b in bounds), -18, 14
    width, height = maximum - minimum + padding * 2, top - bottom + padding * 2
    paths = []
    for name, dx, dy, cluster in placements:
        shift = dx - minimum + padding
        paths.append(outline(glyphs, name, (1, 0, 0, -1, shift, top + padding - dy)))
        if cluster == 3:
            paths.append(polygon(slash_points(), shift, top + padding))
    path = ''.join(paths)
    PUBLIC.mkdir(parents=True, exist_ok=True)
    (PUBLIC / 'demotif-wordmark.svg').write_text(svg(path, width, height))
    (PUBLIC / 'demotif-wordmark-dark.svg').write_text(svg(path, width, height, '#171717'))
    (PUBLIC / 'demotif-wordmark-light.svg').write_text(svg(path, width, height, '#fafafa'))
    symbol = outline(glyphs, 'o', (1, 0, 0, -1, -24, 560)) + polygon(slash_points(), -24, 560)
    (PUBLIC / 'demotif-symbol.svg').write_text(svg(symbol, 540, 590))
    geometry = {'viewBox': f'0 0 {width:.2f} {height:.2f}', 'width': round(width, 2),
                'height': round(height, 2), 'path': path, 'symbol': {'viewBox': '0 0 540 590', 'path': symbol}}
    (ROOT / 'src/components/brand-geometry.ts').write_text('// Generated by scripts/generate_brand.py. Do not edit outlines by hand.\nexport const brandGeometry = ' + json.dumps(geometry, indent=2) + ' as const\n')
    favicon = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48"><title>Demotif</title>'
               f'<rect width="48" height="48" rx="10" fill="#171717"/>'
               f'<g transform="translate(9 7) scale(.055)" fill="#fafafa"><path d="{symbol}"/></g></svg>\n')
    (ROOT / 'public/favicon.svg').write_text(favicon)
    print(f'Geist {WEIGHT}, custom slash {SLASH_WIDTH}; wordmark {width:.2f} × {height:.2f}')


if __name__ == '__main__':
    main()
